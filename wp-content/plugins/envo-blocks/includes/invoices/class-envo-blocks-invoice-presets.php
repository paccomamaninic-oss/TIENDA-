	/**
	 * One preset with all keys.
	 *
	 * @param string $key Preset key.
	 * @return array
	 */
	public static function get( $key ) {
		$all    = self::all();
		$preset = isset( $all[ $key ] ) ? $all[ $key ] : $all['international'];
		return array_merge(
			array(
				'texts'    => array(),
				'footer'   => '',
				'title'    => '',
				'tax'      => '',
				'grouping' => 'intl',
				'recap'    => 'wc',
				'words'    => false,
				'year'     => 1,
				'fields'   => array(),
				'packs'    => array(),
				'warning'  => '',
			),
			$preset
		);
	}

	/**
	 * Preset that fits a WooCommerce base country.
	 *
	 * @param string $country Country code.
	 * @return string
	 */
	public static function for_country( $country ) {
		$map = array(
			'CZ' => 'cz',
			'SK' => 'sk',
			'DE' => 'de',
			'AT' => 'at',
			'PL' => 'pl',
			'FR' => 'fr',
			'GB' => 'uk',
			'US' => 'us',
			'CA' => 'ca',
			'AU' => 'au',
			'TR' => 'tr',
			'IN' => 'in',
			'JP' => 'jp',
			'AE' => 'ae',
			'SA' => 'sa',
			'BR' => 'br',
		);
		if ( isset( $map[ $country ] ) ) {
			return $map[ $country ];
		}
		return in_array( $country, self::eu_countries(), true ) ? 'eu' : 'international';
	}

